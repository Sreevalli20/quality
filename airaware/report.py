"""Personal air-quality report generator (Markdown download)."""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Optional

from .aqi import POLLUTANTS
from .data import MeasurementSet
from .planner import TIME_SLOTS
from .recommendations import Recommendation, UserProfile

_SLOT_LABELS = {key: label for key, label, _ in TIME_SLOTS}


def build_report(measurement: Optional[MeasurementSet],
                 profile: Optional[UserProfile],
                 recs: Optional[dict[str, list[Recommendation]]] = None,
                 plan_guidance: Optional[dict[str, str]] = None) -> str:
    """Build a Markdown personal report. All figures come from the
    supplied measurement - nothing is invented."""
    lines: list[str] = []
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    lines.append("# AirAware AI — Personal Air Quality Report")
    lines.append("")
    lines.append(f"Generated: {now}")
    lines.append("")

    if measurement is None or measurement.display_aqi is None:
        lines.append("No air-quality measurement was loaded when this report "
                     "was generated. Load data in the app and regenerate.")
        return "\n".join(lines)

    m = measurement
    lines.append("## Measurement")
    lines.append("")
    lines.append(f"- **Location:** {m.location or 'unspecified'}")
    lines.append(f"- **Timestamp:** {m.timestamp.strftime('%Y-%m-%d %H:%M UTC')}")
    lines.append(f"- **Source:** {m.source_label}")
    if m.is_sample:
        lines.append("- **Status:** SAMPLE DEMONSTRATION DATA — not a live reading")
    lines.append(f"- **Overall AQI:** {m.display_aqi:.1f} "
                 f"({m.category_name or 'unknown category'})")
    lines.append("")

    if m.result and m.result.pollutant_results:
        lines.append("## Pollutant breakdown (CPCB sub-indices)")
        lines.append("")
        lines.append("| Pollutant | Concentration | Sub-index |")
        lines.append("|---|---|---|")
        for r in m.result.pollutant_results:
            info = POLLUTANTS[r.pollutant]
            lines.append(f"| {info['name']} ({info['period']}) | "
                         f"{r.concentration:g} {r.unit} | {r.sub_index:.0f} |")
        lines.append("")
        if m.result.dominant_pollutant:
            dom = next(r for r in m.result.pollutant_results
                       if r.pollutant == m.result.dominant_pollutant)
            lines.append(f"**Dominant pollutant:** {POLLUTANTS[dom.pollutant]['name']} "
                         f"— it sets the overall AQI under the CPCB max rule.")
            lines.append("")
        if m.result.is_partial:
            lines.append("> Partial measurement: unmeasured pollutants could "
                         "raise the true AQI.")
            lines.append("")

    if profile is not None:
        lines.append("## Your profile")
        lines.append("")
        lines.append(f"- {profile.summary()}")
        lines.append(f"- Outdoor activity preference: {profile.outdoor_pref}")
        lines.append(f"- Budget: {profile.budget} · Priority: {profile.priority}")
        if profile.concerns:
            lines.append(f"- Concerns: {', '.join(profile.concerns)}")
        lines.append("")

    if recs:
        labels = {
            "understanding": "Understanding the situation",
            "today": "What to do today",
            "avoid": "What to avoid",
            "alternatives": "Lower-emission alternatives",
            "indoor": "Indoor protection",
            "next_steps": "Why it matters & next steps",
        }
        lines.append("## Recommendations")
        lines.append("")
        lines.append("_Generated by AirAware AI's deterministic rule engine._")
        lines.append("")
        for key, label in labels.items():
            items = recs.get(key, [])
            if not items:
                continue
            lines.append(f"### {label}")
            lines.append("")
            for r in sorted(items, key=lambda x: x.priority):
                lines.append(f"- **{r.title}** — {r.detail} "
                             f"_Why: {r.reason}_")
            lines.append("")

    if plan_guidance:
        lines.append("## My daily plan")
        lines.append("")
        for slot, label in _SLOT_LABELS.items():
            text = plan_guidance.get(slot)
            if text:
                lines.append(f"- **{label}:** {text}")
        for slot, text in plan_guidance.items():
            if slot not in _SLOT_LABELS:
                lines.append(f"- **{slot}:** {text}")
        lines.append("")

    lines.append("---")
    lines.append("*AirAware AI · PromptWars Challenge 06 · CPCB AQI "
                 "methodology · rule-based guidance. Estimates and "
                 "demonstration data are labelled as such.*")
    return "\n".join(lines)
