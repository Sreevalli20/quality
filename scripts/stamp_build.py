"""Regenerate airaware/build_info.py before a deployment commit.

Stamps the app with its version, the git commit it was built from, a
build identifier, and a fingerprint over the shipped sources so the
running deployment can be matched to an exact tree.

Usage:  python scripts/stamp_build.py
"""

from __future__ import annotations

import hashlib
import re
import subprocess
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "airaware"
OUT = PACKAGE / "build_info.py"
INIT = PACKAGE / "__init__.py"


def _version() -> str:
    m = re.search(r'__version__\s*=\s*["\']([^"\']+)', INIT.read_text())
    return m.group(1) if m else "0.0.0"


def _git_sha() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=ROOT,
            capture_output=True, text=True, check=True)
        return out.stdout.strip()
    except Exception:
        return "unknown"


def source_hash() -> str:
    """Fingerprint of every shipped source file (build_info excluded)."""
    h = hashlib.sha256()
    files = [ROOT / "app.py", ROOT / "requirements.txt"]
    files += sorted(PACKAGE.glob("*.py"))
    for f in files:
        if f == OUT:
            continue
        h.update(f.name.encode())
        h.update(b"\0")
        h.update(f.read_bytes())
        h.update(b"\0")
    return h.hexdigest()[:16]


def main() -> None:
    sha = _git_sha()
    built = datetime.now(timezone.utc)
    build_id = f"{built:%Y%m%d}-{sha[:7] or 'local'}"
    OUT.write_text(
        '"""Build stamp - generated by scripts/stamp_build.py.\n\n'
        'Do not edit by hand; re-run the script before deploying.\n'
        '"""\n\n'
        f'APP_VERSION = "{_version()}"\n'
        f'GIT_SHA = "{sha}"\n'
        f'BUILD_ID = "{build_id}"\n'
        f'BUILT_AT = "{built:%Y-%m-%d %H:%M UTC}"\n'
        f'SOURCE_HASH = "{source_hash()}"\n',
        encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: version={_version()} "
          f"sha={sha[:12]} build={build_id} src={source_hash()}")


if __name__ == "__main__":
    main()
